-- Search Clubs Function
CREATE OR REPLACE FUNCTION search_clubs_json(search_term text)
RETURNS jsonb AS $$
DECLARE
  result jsonb;
BEGIN
  SELECT jsonb_agg(club)
  INTO result
  FROM (
    SELECT 
      id, 
      name
    FROM 
      public.clubs
    WHERE 
      name ILIKE '%' || search_term || '%'
    LIMIT 50
  ) AS club;

  RETURN result;
END;
$$ LANGUAGE plpgsql;

