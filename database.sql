-- Trigger: Handle New User (auth.users -> public.users)
CREATE OR REPLACE FUNCTION handle_new_user()
RETURNS trigger AS $$
BEGIN
  INSERT INTO public.users (
    id, 
    name, 
    username, 
    avatar_url, 
    created_at
  )
  VALUES (
    new.id,
    COALESCE(new.raw_user_meta_data->>'name', ''),
    COALESCE(new.raw_user_meta_data->>'username', ''),
    NULL,
    NOW()
  );
  RETURN new;
END;
$$ LANGUAGE plpgsql;

